    private void digitar(String numero) {

        if (novoNumero) {
            display.setText(numero);        
            novoNumero = false;

        } else {
            String texto = display.getText();

            String digitos = texto.replace("-", "");   

            if (digitos.length() < 3) {
                if (texto.equals("0")) {                
                    display.setText(numero);            
                } else {
                    display.setText(texto + numero);    
                }
            }
        }
    }

    private void operar(String novaOperacao) {
 
        if (display.getText().equals("Erro")) {
            return;
        }
 
        if (!operador.isEmpty() && !novoNumero) {
            calcular();
 
            if (display.getText().equals("Erro")) {
                return;
            }
        }
 
        primeiroNumero = Long.parseLong(display.getText()); 
        operador = novaOperacao;
        novoNumero = true;
    }
 
    private void calcular() {
 
        if (operador.isEmpty() || display.getText().equals("Erro")) {
            return;
        }
 
        long segundoNumero = Long.parseLong(display.getText());
        long resultado;

        switch (operador) {

            case "+":
                resultado = primeiroNumero + segundoNumero;
                break;

            case "-":
                resultado = primeiroNumero - segundoNumero;
                break;

            case "*":
                resultado = primeiroNumero * segundoNumero;
                break;

            case "/":
                if (segundoNumero == 0) {
                    display.setText("Erro");
                    System.out.println("Erro");
                    operador = "";
                    novoNumero = true;
                    return;
                }

                resultado = primeiroNumero / segundoNumero;     
               

            default:
                return;
        }

        display.setText(String.valueOf(resultado));     
        System.out.println(primeiroNumero + " " + operador + " " + segundoNumero + " = " + resultado);
 
        primeiroNumero = resultado;     
        operador = "";                 
        novoNumero = true;
    }

    private void resetar() {            // botao C
        display.setText("0");
        primeiroNumero = 0;
        operador = "";
        novoNumero = true;
    }

    private void alterarSinal() {       // botao +/-

        if (novoNumero) {       
            return;
        }

        long numero = Long.parseLong(display.getText());
        display.setText(String.valueOf(numero * -1));
    }
    
    private void apagarDigito() {       // botao de apagar

        String texto = display.getText();

        if (texto.equals("Erro")) {     // se erro, reseta
            resetar();
            return;
        }

        if (novoNumero) {           
            return;
        }

        if (texto.length() == 1 || (texto.startsWith("-") && texto.length() == 2)) {
            display.setText("0");
        } else {
            display.setText(texto.substring(0, texto.length() - 1));
        }
    }

